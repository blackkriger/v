export const statsLine = (place: number, name: string, left: boolean, count: number) =>
  `${place}. ${name}${left ? ' (вышел)' : ''} — ${count} ${pluralTimes(count)}`;

function pluralTimes(n: number): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  return mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14) ? 'раза' : 'раз';
}
